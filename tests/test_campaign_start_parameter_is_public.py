"""РЕК-6А: форма кампании обязана предупреждать, что метку видит клиент.

Метка (`start_parameter`) — ПУБЛИЧНАЯ по устройству Телеграма: заходя по рекламной ссылке,
человек отправляет в свой чат `/start <метка>`, и сообщение там остаётся. Владелец называет
кампании внутренними кличками с рекламным бюджетом («Кувалда 7000₽»); метка `kuvalda7000`
вернула бы утечку, которую закрыл РЕК-1, — мимо всякого кода, потому что кодом это не чинится.

Ни одна из двух админских форм об этом не говорила: чат-админка предлагала «латинские буквы,
цифры, - или _», кабинет — «Только латиница, цифры, _ и -».

⚠️ ГРАНИЦА, названная честно: сторож проверяет ОБЪЕКТ — константу, на которую переведены обе
формы, — а не содержимое файла. Что константа реально доходит до экрана, он не доказывает:
это два `await message.answer` внутри FSM-обработчиков, поднимать их ради подсказки дороже
пользы. Защищает от «кто-то стёр предупреждение» и от «формы разъехались», не больше.
"""

from app.handlers.admin.campaigns import START_PARAMETER_PUBLIC_WARNING


def test_warning_says_the_client_will_see_the_tag():
    text = START_PARAMETER_PUBLIC_WARNING.lower()
    assert 'клиент' in text, 'предупреждение перестало называть того, кто метку увидит'
    assert 'увидит' in text or 'видит' in text, 'предупреждение перестало говорить, что метку ВИДНО'


def test_warning_forbids_the_two_things_that_actually_leaked():
    """Не общее «будьте осторожны», а ровно то, что владелец пишет в имени кампании."""
    text = START_PARAMETER_PUBLIC_WARNING.lower()
    assert 'внутренн' in text, 'предупреждение перестало запрещать внутреннее название'
    assert 'бюджет' in text, 'предупреждение перестало запрещать бюджет — а он и утекал'


def test_both_forms_use_the_same_constant():
    """Форма создания и форма правки не должны разъехаться: у них один источник текста."""
    import inspect

    from app.handlers.admin import campaigns

    source = inspect.getsource(campaigns)
    uses = source.count('START_PARAMETER_PUBLIC_WARNING')
    # одно объявление + два использования; меньше — значит одна из форм отвалилась
    assert uses >= 3, f'константу используют {uses - 1} раз(а) вместо двух — формы разъехались'
