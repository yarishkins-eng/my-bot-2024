"""РС-14д: сторож на подсказку о пределах медиа в кабинете.

Экран рассылок пишет человеку словами: «Картинка до 10 МБ, видео до 50 МБ». Это текст-инструкция,
а такие протухают молча: числа живут в конфиге бота, а фраза — в четырёх локалях кабинета, в другом
репозитории. Сторож краснеет ровно тогда, когда текст стал неправдой.

⛔ Если тест упал — не «поправить число здесь». Сначала решить, менялись ли пределы намеренно, и
если да — обновить фразу `admin.broadcasts.mediaHint` во ВСЕХ четырёх локалях кабинета
(`cabinet-code/src/locales/{ru,en,fa,zh}.json`), а уже потом это ожидание.
"""

from app.config import settings


# Числа, которые СЕГОДНЯ написаны человеку на экране создания рассылки.
HINT_IMAGE_MB = 10
HINT_VIDEO_MB = 50


def test_media_hint_still_tells_the_truth() -> None:
    assert settings.MEDIA_MAX_IMAGE_SIZE_MB == HINT_IMAGE_MB, (
        'подсказка кабинета обещает картинку до 10 МБ — предел изменился, фраза стала ложью'
    )
    assert settings.MEDIA_MAX_VIDEO_SIZE_MB == HINT_VIDEO_MB, (
        'подсказка кабинета обещает видео до 50 МБ — предел изменился, фраза стала ложью'
    )


def test_caption_limit_in_hint_matches_the_splitter() -> None:
    """Та же подсказка называет 1024 знака — проверяем ПОВЕДЕНИЕ, а не наличие числа в файле.

    Сторож на подстроку в исходнике ничего не стережёт: число встречается и в комментариях.
    Спрашиваем сам код: на 1024 знаках подпись ещё влезает, на 1025 — уже нет.
    """
    from app.services.broadcast_service import caption_exceeds_telegram_limit

    assert caption_exceeds_telegram_limit('я' * 1024) is False, 'подсказка обещает, что 1024 влезает'
    assert caption_exceeds_telegram_limit('я' * 1025) is True, 'подсказка обещает деление после 1024'
